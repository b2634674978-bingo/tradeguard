"""驱动兼容层的方言翻译测试（不需要真实 Postgres 服务）。"""

from __future__ import annotations

import pytest

from tradeguard.database import Database, schema_statements
from tradeguard.dbdriver import (
    SqliteBackend,
    make_backend,
    mask_url,
    normalize_pg_url,
    split_statements,
    translate_placeholders,
    translate_statement,
)


def test_placeholder_translation():
    assert translate_placeholders("SELECT * FROM t WHERE a = ? AND b = ?") == (
        "SELECT * FROM t WHERE a = %s AND b = %s"
    )


def test_placeholder_skips_string_literals():
    sql = "CREATE TABLE t (a TEXT DEFAULT '', b TEXT) VALUES (?)"  # 引号内的内容不参与替换
    assert translate_placeholders(sql).count("%s") == 1


def test_insert_or_ignore_becomes_on_conflict_do_nothing():
    sql = "INSERT OR IGNORE INTO report_phones (report_id, phone_norm, role) VALUES (?, ?, 'subject')"
    out = translate_statement(sql)
    assert out.startswith("INSERT INTO report_phones")
    assert out.endswith("ON CONFLICT DO NOTHING")
    assert "?" not in out
    assert "%s" in out


def test_insert_or_replace_becomes_upsert_on_primary_key():
    sql = "INSERT OR REPLACE INTO meta(key, value) VALUES (?, ?)"
    out = translate_statement(sql)
    assert out.startswith("INSERT INTO meta(key, value)")
    assert "ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value" in out


def test_sqlite_dialect_keeps_qmark_placeholders():
    sql = "INSERT OR IGNORE INTO report_phones (report_id, phone_norm) VALUES (?, ?)"
    out = translate_statement(sql, dialect="sqlite")
    assert "?" in out
    assert "%s" not in out
    assert out.endswith("ON CONFLICT DO NOTHING")


def test_plain_select_is_untouched():
    sql = "SELECT * FROM reports WHERE status = ?"
    assert translate_statement(sql) == "SELECT * FROM reports WHERE status = %s"


def test_split_statements_drops_empty_fragments():
    script = "CREATE TABLE a (id INTEGER);\n\nCREATE INDEX i ON a(id);\n"
    statements = split_statements(script)
    assert len(statements) == 2
    assert statements[1].startswith("CREATE INDEX")


def test_schema_uses_sqlite_types_for_sqlite_backend(temp_dir):
    statements = "\n".join(schema_statements(SqliteBackend(temp_dir / "x.db")))
    assert "AUTOINCREMENT" in statements
    assert "BLOB NOT NULL" in statements
    assert "BYTEA" not in statements


def test_schema_uses_postgres_types_for_postgres_backend():
    pytest.importorskip("psycopg")
    from tradeguard.dbdriver import PostgresBackend

    backend = PostgresBackend("postgresql://user:secret@localhost:5432/tradeguard")
    statements = "\n".join(schema_statements(backend))
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in statements
    assert "BYTEA NOT NULL" in statements
    assert "DOUBLE PRECISION" in statements
    assert "AUTOINCREMENT" not in statements


def test_normalize_postgres_scheme_and_masking():
    dsn, kwargs, host = normalize_pg_url("postgres://user:p%40ss@db.example.com:5432/tradeguard")
    assert dsn.startswith("postgresql://")
    assert kwargs == {}
    assert host == "db.example.com:5432/tradeguard"
    assert mask_url("postgres://user:p%40ss@db.example.com:5432/tradeguard") == (
        "postgresql://user:***@db.example.com:5432/tradeguard"
    )


def test_pooler_dsn_disables_prepared_statements():
    # Supabase 事务模式池化端口 6543 不支持命名预处理语句
    dsn, kwargs, _host = normalize_pg_url(
        "postgresql://u:p@aws-0-ap-southeast-1.pooler.supabase.com:6543/postgres?pgbouncer=true&sslmode=require"
    )
    assert "pgbouncer" not in dsn
    assert "sslmode=require" in dsn
    assert kwargs["prepare_threshold"] is None


def test_direct_connection_keeps_prepared_statements():
    _dsn, kwargs, _host = normalize_pg_url("postgresql://u:p@db.neon.tech:5432/tradeguard?sslmode=require")
    assert "prepare_threshold" not in kwargs


def test_explicit_path_forces_sqlite_even_with_database_url(temp_dir):
    db = Database(temp_dir / "forced.db", database_url="postgresql://u:p@localhost:5432/x")
    assert db.engine == "sqlite"
    assert db.supports_file_backup is True


def test_make_backend_defaults_to_sqlite(temp_dir):
    backend = make_backend(temp_dir / "plain.db")
    assert backend.name == "sqlite"


def test_backup_and_restore_roundtrip(temp_dir):
    db = Database(temp_dir / "backup.db")
    db.add_report(phones=["+1 555 010 9999"], narrative="备份恢复测试记录。")
    snapshot = db.backup_bytes()
    assert snapshot.startswith(b"SQLite format 3\x00")

    db.clear_all()
    assert db.quick_counts()["reports"] == 0
    db.restore_from_bytes(snapshot)
    assert db.quick_counts()["reports"] >= 1


def test_restore_rejects_non_sqlite_payload(temp_dir):
    db = Database(temp_dir / "guard.db")
    with pytest.raises(ValueError):
        db.restore_from_bytes(b"not a database")
